//! Domain model. Platform-agnostic: no SQL, no Android, no FFI types.
//!
//! Three kinds of data:
//! - Entities are mutable and synced. [`Reminder`] is what the user defined and
//!   [`Progress`] is how far its plan has advanced. They are separate so that
//!   editing on one device and resolving on another do not overwrite each other.
//! - Events ([`Resolution`]) are an append-only archive. They are written when a
//!   reminder is resolved and read only by history and statistics, never by
//!   scheduling or completion logic.
//! - Derived or device-local state (next fire time, scheduled alarms, snooze,
//!   delivered notifications) is never part of this model. It is rebuilt from
//!   the entities, the clock and the device time zone.
//!
//! Invalid states are ruled out by the types where possible. Shapes that cannot
//! be expressed structurally use the validated types in [`values`], which can
//! only be built through their constructors.

