use std::num::NonZeroU32;

use jiff::{Timestamp, civil};
use uuid::Uuid;

pub use values::{ClockTimes, DayOfMonth, InvalidValue, PositiveDuration, Weekdays, Window};

/// Reminder identifier: a UUIDv7 generated by whoever creates the reminder.
/// Other versions are accepted when reading but not enforced.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ReminderId(pub Uuid);

impl ReminderId {
    /// A new identifier, ordered by `now`.
    pub fn new(now: Timestamp) -> Self {
        Self(new_v7(now))
    }
}

/// Resolution identifier: a UUIDv7 generated by whoever records the resolution.
/// Other versions are accepted when reading but not enforced.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ResolutionId(pub Uuid);

impl ResolutionId {
    /// A new identifier, ordered by `now`.
    pub fn new(now: Timestamp) -> Self {
        Self(new_v7(now))
    }
}

/// A UUIDv7 stamped with `now`, to millisecond precision. The clock is passed in
/// so the core never reads it. UUIDv7 cannot represent instants before the Unix
/// epoch, so those are stamped as the epoch.
fn new_v7(now: Timestamp) -> Uuid {
    let seconds = u64::try_from(now.as_second()).unwrap_or(0);
    let nanos = u32::try_from(now.subsec_nanosecond()).unwrap_or(0);
    Uuid::new_v7(uuid::Timestamp::from_unix(uuid::NoContext, seconds, nanos))
}

/// A thing to be reminded about, plus when and how to alert for it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Reminder {
    pub id: ReminderId,
    pub title: String,
    pub notes: String,
    pub plan: Plan,
    /// Set when the user archives the reminder (hidden, no alerts).
    pub archived_at: Option<Timestamp>,
    pub meta: Meta,
}

/// Synchronisation bookkeeping for a mutable entity.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Meta {
    /// Increases on every accepted write. Writers pass the revision they read
    /// as the base of an edit.
    pub revision: u64,
    pub created_at: Timestamp,
    pub updated_at: Timestamp,
    /// Tombstone. A deleted reminder is kept so deletion can sync.
    pub deleted_at: Option<Timestamp>,
}

/// How completion works for a reminder. A sum type, so a single-completion
/// reminder cannot also have a recurrence.
///
/// Only a scheduled plan carries an [`Alert`]. An unscheduled plan never fires,
/// so it has nothing to alert about.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Plan {
    /// Finished when its [`Progress`] records a completion.
    Once { due: Option<Due> },
    /// Never finishes. Every resolution is recorded.
    Ongoing { cadence: Option<Cadence> },
}

/// A single point in time to alert at.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Due {
    pub when: When,
    pub alert: Alert,
}

/// A repeating schedule to alert on.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Cadence {
    pub recurrence: Recurrence,
    pub alert: Alert,
}

/// A wall-clock time in a zone. The instant it denotes is derived, because
/// zone rules and the device zone (for [`Zone::Floating`]) can change.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct When {
    pub local: civil::DateTime,
    pub zone: Zone,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Zone {
    /// Follows whatever zone the device is in.
    Floating,
    /// A specific IANA zone name, such as `Europe/Berlin`. Deliberately not
    /// validated here: whether a name is known depends on the time zone
    /// database of the device resolving it. Check it when resolving a time.
    Fixed(String),
}

/// A repeating schedule. Occurrences are derived from this, never stored.
///
/// `rule` selects the days and `at` selects the times within each selected
/// day. Everything is evaluated as local wall-clock time in `zone`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Recurrence {
    /// First day the rule can fire on. Also anchors the day for monthly and
    /// yearly rules.
    pub starts_on: civil::Date,
    pub zone: Zone,
    pub rule: Rule,
    pub at: TimesOfDay,
    pub end: Option<End>,
}

/// Which days a [`Recurrence`] fires on. `every` counts days, weeks, months or
/// years between firings.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Rule {
    Daily { every: NonZeroU32 },
    Weekly { every: NonZeroU32, on: Weekdays },
    Monthly { every: NonZeroU32, on: MonthlyOn },
    Yearly { every: NonZeroU32 },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MonthlyOn {
    Day(DayOfMonth),
    NthWeekday { nth: Nth, weekday: civil::Weekday },
}

/// Which occurrence of a weekday in a month. There is no fifth, because not
/// every month has one. Use [`Nth::Last`] instead.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Nth {
    First,
    Second,
    Third,
    Fourth,
    Last,
}

/// Clock times to fire at on each day a [`Rule`] selects.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TimesOfDay {
    /// Fixed clock times, such as 09:00, 13:00 and 21:00.
    At(ClockTimes),
    /// Repeats within a window of the day.
    Every(Window),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum End {
    /// No occurrence after this local time.
    Until(civil::DateTime),
    /// Stop after this many occurrences. Counts individual firings, not days.
    Count(NonZeroU32),
}

/// How a reminder alerts. Describes intent. The platform layer maps it to
/// notification channels, alarm APIs and so on.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Alert {
    pub style: AlertStyle,
    /// Re-alert until the occurrence is resolved. Applies to either style.
    pub nudge: Option<Nudge>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AlertStyle {
    /// A notification. `sticky` keeps it in the shade until handled, rather
    /// than letting it be swiped away.
    Notification { sticky: bool },
    /// An OS alarm that keeps ringing until dismissed.
    Alarm,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Nudge {
    pub every: PositiveDuration,
    /// Stop after this many nudges. `None` nudges until resolved.
    pub limit: Option<NonZeroU32>,
}

/// A slot in a recurrence, identified by its nominal local time. This is not the
/// instant it fires at, which depends on the zone and its rules.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Slot(pub civil::DateTime);

/// How far a reminder's plan has advanced. Together with the [`Reminder`], this
/// is all that scheduling and completion logic read.
///
/// The state must match the reminder's [`Plan`]: [`ProgressState::Once`] for
/// `Plan::Once`, [`ProgressState::Cadence`] for `Plan::Ongoing` with a cadence.
/// A tracker has no progress.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Progress {
    pub reminder_id: ReminderId,
    pub state: ProgressState,
    /// Increases on every accepted write.
    pub revision: u64,
    pub updated_at: Timestamp,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ProgressState {
    Once {
        /// When it was completed. `None` while open.
        done_at: Option<Timestamp>,
    },
    Cadence {
        current: Watermark,
        /// The watermark before the last resolution, so that resolution can be
        /// undone. `None` when there is nothing to undo.
        previous: Option<Watermark>,
    },
}

/// How far a cadence has been handled. Slots up to and including `through` are
/// handled, whether done, skipped or missed. The next pending slot is the first
/// one after it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Watermark {
    pub through: Option<Slot>,
    /// Number of slots handled so far, for [`End::Count`]. Stored here so that
    /// editing the recurrence does not change it.
    pub handled: u32,
}

/// An archival record of a response to a reminder: done or skipped. Immutable
/// once written. It is written alongside the [`Progress`] change it causes and
/// is read only by history and statistics. Scheduling and completion logic never
/// read it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Resolution {
    pub id: ResolutionId,
    pub reminder_id: ReminderId,
    pub resolved_at: Timestamp,
    pub outcome: Outcome,
    pub note: Option<String>,
    /// Tombstone. Undoing a resolution marks it deleted rather than removing it.
    pub deleted_at: Option<Timestamp>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Outcome {
    /// Did it. `slot` is the scheduled slot it was for. `None` for an ad-hoc
    /// completion, such as a one-off or a tracker log.
    Done { slot: Option<Slot> },
    /// Deliberately passed on a scheduled slot. A skip only makes sense for a
    /// slot, so it is required.
    Skipped { slot: Slot },
}
